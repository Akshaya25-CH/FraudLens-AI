def create_dataset():
    eval_dir = PROJECT_ROOT / "datasets" / "evaluation"
    eval_dir.mkdir(parents=True, exist_ok=True)
    eval_file = eval_dir / "indian_sms_eval.csv"

    print(f"Creating evaluation dataset: {eval_file}")
    with open(eval_file, mode="w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow(["id", "label", "category", "language", "message", "source"])
        for row in EVAL_SAMPLES:
            writer.writerow(row)

    print(f"Successfully wrote {len(EVAL_SAMPLES)} evaluation samples.")
    assert len(EVAL_SAMPLES) == 100, f"Expected exactly 100 rows, got {len(EVAL_SAMPLES)}"

    scam_count = sum(1 for r in EVAL_SAMPLES if r[1] == 1)
    legit_count = sum(1 for r in EVAL_SAMPLES if r[1] == 0)
    print(f"Distribution: Scam (label=1) = {scam_count}, Legit (label=0) = {legit_count}")
    assert scam_count == 50 and legit_count == 50, "Class balance must be exactly 50/50!"

if __name__ == "__main__":
    create_dataset()
